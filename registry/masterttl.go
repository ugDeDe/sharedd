package main

// Принудительная ротация мастерства по лимиту времени.
//
// master_ttl_minutes ([rotation]) — максимум непрерывного времени ноды
// мастером ОДНОГО домена. По истечении evaluateAssignments насильно передаёт
// домен следующей здоровой ноде (наименее загруженной из очереди, сам
// истёкший держатель исключён): получается равномерный round-robin мастерства.
// Нода при этом НЕ покидает очередь — через TTL она может получить домен
// обратно (или другой домен раньше, как самая разгруженная).
//
// Момент назначения (AssignmentsSince) хранится в state — отсчёт переживает
// рестарт регистратора. Перенос назначения на новый node_id с тем же IP
// (ре-регистрация) отсчёт НЕ сбрасывает: клиентский сервис на той же
// железке не прерывался, лишняя ротация не нужна.
//
// Изменение лимита применяется на лету и действует на уже идущие stint'ы:
// уменьшили ниже текущего возраста мастера — ротация на ближайшем тике
// selectionLoop; увеличили — текущий мастер спокойно досидит до нового лимита.
// Замены НЕТ (единственная здоровая нода — сама держатель): домен остаётся
// на ней (событие не спамим, в панели виден статус «TTL истёк»), ротация
// случится на первом же тике с появившейся здоровой нодой.
//
//	0 = лимит выключен (мастер держит домен, пока здоров — поведение.x);
//	нет ключа = дефолт 30 минут.

import "time"

const (
	defaultMasterTTLMinutes = 30
	// maxMasterTTLMinutes — верхняя граница валидации из панели (30 суток).
	maxMasterTTLMinutes = 43200
)

// resolveMasterTTLMinutes — эффективный лимит (мин): nil → дефолт, 0 → выкл.
func resolveMasterTTLMinutes(p *int) int {
	if p == nil {
		return defaultMasterTTLMinutes
	}
	return *p
}

// masterTTL — эффективный лимит как Duration (0 = выкл.). Горячее чтение —
// под cfgMu (панель правит на лету).
func (r *Registry) masterTTL() time.Duration {
	r.cfgMu.RLock()
	defer r.cfgMu.RUnlock()
	return time.Duration(resolveMasterTTLMinutes(r.cfg.Rotation.MasterTTLMinutes)) * time.Minute
}
